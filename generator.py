def macros_from_items(items):
    total = {"calories": 0.0, "protein": 0.0, "carb": 0.0, "fat": 0.0}
    for name, grams in items:
        vals = NUTRITION_DB.get(name)
        if not vals:
            continue
        kcal, p, c, f = vals
        factor = grams / 100.0
        total["calories"] += kcal * factor
        total["protein"] += p * factor
        total["carb"] += c * factor
        total["fat"] += f * factor
    return {k: int(round(v)) for k, v in total.items()}

