class MealGenerator:
    def __init__(self, redis_conn=None):
        global redis_client
        if redis_conn and redis_available:
            redis_client = redis_conn

        self.foods_db = self._load_compressed_db()

    def _load_compressed_db(self):
        # Bump this whenever the hardcoded `foods` dict below changes. Without a version
        # in the cache key, an already-running deployment would keep serving the OLD food
        # list from Redis (cached for 30 days) even after you push a code update with new
        # meals - the cache would silently mask the change for up to a month.
        # v3: switched from plain-string meals + formula-based macros to structured
        # {text, items} entries with macros computed from real ingredient data (see
        # NUTRITION_DB above) - must bump the version so a deployment doesn't load old
        # v2 plain-string data from Redis and crash trying to read it as a dict.
        db_version = "v3"
        cache_key = f"foods_db_compressed_{db_version}"

        if redis_available and redis_client:
            try:
                db = redis_client.get(cache_key)
                if db:
                    return json.loads(db)
            except Exception:
                pass

        foods = FOODS  # structured {text, items} entries - see NUTRITION_DB above

        if redis_available and redis_client:
            try:
                redis_client.setex(cache_key, 2592000, json.dumps(foods, ensure_ascii=False))
            except Exception:
                pass

        return foods

    def _cache_key(self, user_data, day_num):
        raw = f"{user_data.get('user_id','0')}_{user_data.get('diet_type','معمولی')}_{user_data.get('goal','حفظ تناسب')}_{user_data.get('bmr',2000)}_{day_num}"
        user_hash = hashlib.md5(raw.encode()).hexdigest()[:12]
        return f"daily_plan:{user_hash}:{day_num}"

    def generate_daily_plan(self, user_data, day_number):
        cache_key = self._cache_key(user_data, day_number)

        if redis_available and redis_client:
            try:
                cached = redis_client.get(cache_key)
                if cached:
                    return json.loads(cached)
            except Exception:
                pass
        else:
            if cache_key in local_cache:
                return local_cache[cache_key]

        plan = self._generate_daily_uncached(user_data, day_number)

        if redis_available and redis_client:
            try:
                redis_client.setex(cache_key, 86400, json.dumps(plan, ensure_ascii=False))
            except Exception:
                pass
        else:
            local_cache[cache_key] = plan

        return plan

    def _generate_daily_uncached(self, user_data, day_number):
        diet_type = user_data.get("diet_type", "معمولی")
        bmr = int(user_data.get("bmr", 2000))
        calories_split = {"breakfast": 0.25, "lunch": 0.35, "dinner": 0.25, "snack": 0.15}

        foods = self.foods_db.get(diet_type, self.foods_db["معمولی"])

        meal_sources = {
            "breakfast": foods.get("breakfast", []),
            "lunch": foods.get("lunch", []),
            "dinner": foods.get("dinner", []),
            "snack": foods.get("snacks", [])
        }

        day_plan = {}

        for meal_type in ["breakfast", "lunch", "dinner", "snack"]:
            meals_list = meal_sources.get(meal_type, [])
            if not meals_list:
                continue

            meal = self._select_diverse(meals_list, user_data, day_number, meal_type)
            # meal is a structured {"text": ..., "items": [(ingredient, grams), ...]}
            # dict - macros are computed for real from what the meal actually contains,
            # instead of a generic calorie-split-by-percentage formula that had no
            # connection to the food described.
            base_macros = macros_from_items(meal.get("items", []))

            # The written portions are a realistic single serving, not scaled to any
            # particular person's calorie needs. Scale the whole meal proportionally
            # (keeping the real macro RATIO from the actual food) to roughly match this
            # user's personal target for this meal slot - otherwise total daily calories
            # could drift far from their target bmr regardless of what "bmr" was set to.
            target_calories = bmr * calories_split[meal_type]
            base_calories = base_macros.get("calories", 0)
            scale = 1.0
            if base_calories > 0:
                scale = target_calories / base_calories
                scale = max(0.5, min(scale, 2.0))  # avoid absurd portions in either direction

            macros = {k: int(round(v * scale)) for k, v in base_macros.items()}

            text = f"{self._get_emoji(meal_type)} ({self._get_time(meal_type)}): {meal.get('text', '')}"
            if scale < 0.9 or scale > 1.1:
                portion_note = f" [مقدار را برای هدف کالری‌ات ×{scale:.1f} در نظر بگیر]"
                text += portion_note

            day_plan[meal_type] = {
                "text": text,
                "macros": macros
            }

        return day_plan

    def _select_diverse(self, meals_list, user_data, day_num, meal_type="meal"):
        if not meals_list:
            return {"text": "---", "items": []}

        seed_value = f"{user_data.get('user_id','0')}_{meal_type}_{day_num}_{user_data.get('diet_type','معمولی')}"
        rnd = random.Random(hashlib.md5(seed_value.encode()).hexdigest())

        if len(meals_list) == 1:
            return meals_list[0]

        # The "avoid repeating recent days" window used to be a fixed 3 days, which is
        # meaningless once the pool itself only has 3-4 items (e.g. keto/vegetarian) -
        # nearly every day would repeat something from just outside that tiny window.
        # Scale the window with pool size instead, so smaller food lists still avoid
        # repeats for as long as mathematically possible.
        window = min(day_num - 1, len(meals_list) - 1)
        recent_indexes = []
        for prev_day in range(max(1, day_num - window), day_num):
            prev_seed = f"{user_data.get('user_id','0')}_{meal_type}_{prev_day}_{user_data.get('diet_type','معمولی')}"
            prev_rnd = random.Random(hashlib.md5(prev_seed.encode()).hexdigest())
            recent_indexes.append(prev_rnd.randrange(len(meals_list)))

        available_indexes = [i for i in range(len(meals_list)) if i not in recent_indexes]
        if not available_indexes:
            available_indexes = list(range(len(meals_list)))

        selected_index = rnd.choice(available_indexes)
        return meals_list[selected_index]

    def _get_emoji(self, meal_type):
        return {
            "breakfast": "🥣",
            "lunch": "🍛",
            "dinner": "🥗",
            "snack": "🍎"
        }.get(meal_type, "🍽")

    def _get_time(self, meal_type):
        return {
            "breakfast": "۸:۰۰",
            "lunch": "۱۳:۰۰",
            "dinner": "۱۹:۳۰",
            "snack": "۱۶:۰۰"
        }.get(meal_type, "--:--")

