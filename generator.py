class WorkoutGenerator:
    """
    تولید برنامهٔ هفتگی پروگرسیو (4 جلسه در هفته پیش‌فرض).
    خروجی: dict {
      "week": int,
      "sessions": [ { "day":1, "title":"", "exercises":[{"name":"", "sets":3, "reps":"8-12", "notes":""}, ...] } ... ]
    }
    """
    def __init__(self, redis_client=None):
        self.redis = redis_client

        self.pools = {
            "push": {
                True: ["پرس سینه با هالتر", "پرس بالاسینه دمبل", "دیپس بین دو نیمکت", "پوش-آپ با وزنه"],
                False: ["شنا (پوش‌آپ)", "پوش‌آپ دست چرخان", "دیپس صندلی"]
            },
            "pull": {
                True: ["زیربغل هالتر", "زیربغل دمبل تک‌دست", "بارفیکس", "روینگ کابل"],
                False: ["روینگ با حوله (در در)", "سوپرمن", "کش کششی روینگ"]
            },
            "legs": {
                True: ["اسکوات با هالتر", "لانژ با دمبل", "ددلیفت رومانیایی", "پرس پا"],
                False: ["اسکوات وزن بدن", "لانژ پیاده‌روی", "برپی", "استپ آپ روی صندلی"]
            },
            "core": {
                True: ["پلنک با وزنه", "کرانچ با وزنه", "هالتر روسی"],
                False: ["پلنک", "کرانچ", "لانگز ثابت"]
            },
            "full": {
                True: ["برپی با دمبل", "کلین و جرک", "کات‌پرس"],
                False: ["برپی", "مایونتین کلیمبر", "جامپ اسکوات"]
            }
        }

    def _choose(self, category, equipment, count, seed=None):
        pool = self.pools.get(category, {}).get(equipment, [])
        if not pool:
            return []
        rnd = random.Random(seed) if seed is not None else random
        return rnd.sample(pool, min(count, len(pool)))

    def _progress_sets_reps(self, base_sets, base_reps_low, base_reps_high, week_num):
        sets = base_sets + ((week_num - 1) // 3)
        reps_low = base_reps_low + ((week_num - 1) // 2)
        reps_high = base_reps_high + ((week_num - 1) // 2)
        return sets, f"{reps_low}-{reps_high}"

    def generate_weekly_workout(self, user_data, week_num=1, sessions_per_week=4, equipment=True):
        goal = (user_data.get("goal") or "").lower()
        if "کاهش" in goal:
            base_sets = 3
            reps = (12, 20)
        elif "افزایش" in goal:
            base_sets = 3
            reps = (6, 12)
        else:
            base_sets = 3
            reps = (8, 15)

        sessions = []
        structure = ["push", "pull", "legs", "full"]
        for i in range(sessions_per_week):
            cat = structure[i % len(structure)]
            # Seed exercise selection deterministically per user/week/session, matching
            # how meals are chosen - otherwise a cache miss that re-generates this same
            # week's plan (e.g. after a Redis eviction) could hand the user a different
            # workout than what they saw before, which is confusing for someone tracking
            # progressive overload week to week.
            seed_base = f"{user_data.get('user_id', '0')}_{week_num}_{i}_{cat}"
            main_seed = hashlib.md5((seed_base + '_main').encode()).hexdigest()
            core_seed = hashlib.md5((seed_base + '_core').encode()).hexdigest()
            if cat == "full":
                exercise_names = self._choose("full", equipment, 3, seed=main_seed)
            else:
                exercise_names = self._choose(cat, equipment, 3, seed=main_seed)
                core = self._choose("core", equipment, 1, seed=core_seed)
                exercise_names += core

            sets, reps_str = self._progress_sets_reps(base_sets, reps[0], reps[1], week_num)

            exercises = []
            for name in exercise_names:
                ex_sets = sets
                ex_reps = reps_str
                notes = ""
                if not equipment:
                    if "برپی" in name or "جامپ" in name:
                        ex_sets = max(2, sets - 1)
                        ex_reps = "10-15"
                exercises.append({"name": name, "sets": ex_sets, "reps": ex_reps, "notes": notes})

            sessions.append({
                "day": i + 1,
                "title": f"جلسه {i+1} - {cat}",
                "exercises": exercises
            })

        return {
            "week": int(week_num),
            "sessions_per_week": sessions_per_week,
            "equipment": bool(equipment),
            "sessions": sessions,
            "generated_at": datetime.utcnow().isoformat() + "Z"
        }